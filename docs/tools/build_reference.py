from svgflow import external_figures as external, inkscape_fonts as inkscape, text_metrics as metrics

ROOT = Path(__file__).resolve().parents[2]
GROUPS = {
    "canvas": ("Canvas", "drawing.md", [Canvas]),
    "plot": ("Plot and PlotStyle", "plotting.md", [PlotStyle, Plot]),
    "figure": ("Figure", "figures.md", [Figure]),
    "flow": ("Flow and FlowStyle", "flow-diagrams.md", [FlowStyle, Flow]),
    "helpers": ("Fonts and external helpers", "composition-and-export.md", [
        svgflow.ExecutablePaths, svgflow.available_fonts, svgflow.register_font,
        svgflow.text_width, svgflow.wrap_text, svgflow.import_svg_from_file,
        svgflow.tex2svg, metrics.FontSpec, metrics.get_font, metrics.is_bold,
        metrics.is_italic, external.uniquify_svg_ids, inkscape.find_base_fontconfig,
        inkscape.build_fontconfig, inkscape.inkscape_font_env,
    ]),
}


def signature(obj, name):
    """Render source annotations without expanding the library's type aliases."""
    target = obj.__dict__.get("__init__") if inspect.isclass(obj) else obj
    try:
        node = ast.parse(textwrap.dedent(inspect.getsource(target))).body[0]
    except (OSError, TypeError):
        return name + str(inspect.signature(obj))
    if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
        return name + str(inspect.signature(obj))
    args = node.args
    if args.args and args.args[0].arg in {"self", "cls"}:
        args.args.pop(0)
    result = name + "(" + ast.unparse(args) + ")"
    if node.returns and not inspect.isclass(obj):
        result += " -> " + ast.unparse(node.returns)
    return result


def prose(obj):
    """Convert simple Sphinx roles and literals to readable Markdown."""
    doc = inspect.getdoc(obj) or "No additional contract."
    return re.sub(r":\w+:`([^`]+)`", r"`\1`", doc).replace("``", "`")


def parameter_table(obj):
    """List all accepted parameters, defaults, types and keyword-only flags."""
    rows = []
    for name, p in inspect.signature(obj).parameters.items():
        if name in {"self", "cls"}:
            continue
        default = "required" if p.default is inspect.Parameter.empty else repr(p.default)
        if p.kind is inspect.Parameter.VAR_KEYWORD:
            default = "extra keyword arguments"
        kind = "unspecified" if p.annotation is inspect.Parameter.empty else str(p.annotation)
        if p.kind is inspect.Parameter.KEYWORD_ONLY:
            kind += " (keyword-only)"
        safe_kind = kind.replace("|", r"\|")
        rows.append(f"| `{name}` | `{default}` | `{safe_kind}` |")
    if not rows:
        return "This callable takes no arguments.\n"
    return "| Parameter | Default | Type / calling convention |\n| --- | --- | --- |\n" + "\n".join(rows) + "\n"


def entry(obj, name):
    """Render one stable anchor, signature, contract, parameter table and source link."""
    parts = [f'<a id="{name.lower().replace(".", "-")}"></a>\n', f"## {name}\n"]
    if not isinstance(obj, property):
        parts += ["```python\n" + signature(obj, name) + "\n```\n"]
    parts += [prose(obj) + "\n"]
    if inspect.isclass(obj) and "__init__" in obj.__dict__:
        doc = inspect.getdoc(obj.__init__)
        if doc and doc != inspect.getdoc(object.__init__):
            parts += ["**Construction:**\n\n" + prose(obj.__init__) + "\n"]
    if not isinstance(obj, property):
        parts += [parameter_table(obj)]
    target = obj.fget if isinstance(obj, property) else obj
    target = inspect.unwrap(target)
    source = Path(inspect.getsourcefile(target)).resolve().relative_to(ROOT).as_posix()
    parts += [f"[Source](../../{source})\n"]
    return "\n".join(parts)


def render_all():
    """Return relative paths and reference contents without writing files."""
    rendered = {}
    for key, (title, guide, objects) in GROUPS.items():
        parts = [f"# {title}: API reference\n",
                 f"[Documentation home](../README.md) · [Guide](../{guide})\n",
                 "Generated by `python -m docs.tools.build_reference`; edit source docstrings "
                 "and regenerate. Signatures list every accepted parameter; contracts "
                 "explain units, behavior and limits.\n",
                 "`Number` means int, float or a NumPy number; `Point` is an `(x, y)` pair; "
                 "`Color` is an SVG paint string. Units are SVG user units unless stated "
                 "otherwise. Drawing methods returning `None` append elements. `*` "
                 "introduces keyword-only arguments. Styles affect future calls.\n"]
        parts += ["| Alias | Accepted values |\n| --- | --- |\n"
                  "| `Directed` | `False`, `True`/`'end'`, `'start'`, `'both'` |\n"
                  "| `ArrowStyle` | `'curved'`, `'open'`, `'triangle'`, `'stealth'` |\n"
                  "| `TextAnchor` | `'start'`, `'middle'`, `'end'` |\n"
                  "| `TextBaseline` | `'hanging'`, `'middle'`, `'text-top'`, `'auto'` |\n"
                  "| `PositionBaseline` | `'hanging'`, `'middle'`, `'text-top'` |\n"
                  "| `MarkerType` | `'circle'`, `'cross'`, `'square'` |\n"
                  "| `LegendAnchor` | `'NE'`, `'N'`, `'NW'`, `'W'`, `'E'`, `'SW'`, `'S'`, `'SE'` |\n"
                  "| `Port` | `'N'`, `'S'`, `'E'`, `'W'` |\n"
                  "| `SvgBackend` / `Backend` | `'inkscape'`, `'dvisvgm'`, `'pdf2svg'` |\n"
                  "| `ExportType` | `'png'`, `'pdf'` |\n"
                  "| `GradientSpread` | `'pad'`, `'reflect'`, `'repeat'` (currently emits pad only) |\n"
                  "| `NodeShape` | Shape tuple; see [flow guide](../flow-diagrams.md) |\n"]
        for obj in objects:
            parts.append(entry(obj, obj.__name__))
            if not inspect.isclass(obj):
                continue
            public = [(n, v) for n, v in obj.__dict__.items() if not n.startswith("_")
                      and (inspect.isfunction(v) or isinstance(v, (property, classmethod)))]
            if issubclass(obj, Canvas) and obj is not Canvas:
                parts += ["**Inherited drawing API:** all [Canvas methods](canvas.md), "
                          "including text, paths, gradients, imports, `toSvg`, `save` and "
                          "`export`. Inherited primitives use canvas coordinates.\n"]
            if public:
                parts += ["**Own methods/properties:** " + ", ".join(
                    f"[{n}](#{obj.__name__.lower()}-{n.lower()})" for n, _ in public) + ".\n"]
            for name, value in public:
                target = getattr(obj, name) if isinstance(value, classmethod) else value
                parts.append(entry(target, f"{obj.__name__}.{name}"))
        if key == "helpers":
            parts += ["`FontSpec`, `get_font`, the weight/style interpreters, ID rewriter "
                      "and fontconfig helpers are supporting APIs imported from their modules. "
                      "Other entries on this page are package-level exports.\n"]
        rendered[f"docs/api/{key}.md"] = "\n".join(parts)
    return rendered


def main():
    """Write the five reference pages deterministically."""
    for relative, content in render_all().items():
        path = ROOT / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")
    print("Generated 5 API reference pages.")


if __name__ == "__main__":
    main()
